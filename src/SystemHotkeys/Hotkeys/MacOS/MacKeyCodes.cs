namespace SystemHotkeys.Hotkeys.MacOS;

/// <summary>
/// macOS <c>kVK_*</c> key code to Windows virtual-key code mapping, so a macOS key event runs through the
/// same <see cref="VirtualKeys"/> naming and <see cref="HotkeyCombo"/> detection as a Windows one.
/// </summary>
/// <remarks>
/// A <c>kVK_*</c> code names a physical key position on a US ANSI keyboard, not the character the current
/// layout puts there. Not exhaustive, like <see cref="VirtualKeys"/>: an unmapped code is never recognized
/// as a combo's trailing key.
/// </remarks>
public static class MacKeyCodes
{
	private static readonly Dictionary<int, int> _virtualKeys = new()
	{
		[0x00] = 'A',
		[0x01] = 'S',
		[0x02] = 'D',
		[0x03] = 'F',
		[0x04] = 'H',
		[0x05] = 'G',
		[0x06] = 'Z',
		[0x07] = 'X',
		[0x08] = 'C',
		[0x09] = 'V',
		[0x0B] = 'B',
		[0x0C] = 'Q',
		[0x0D] = 'W',
		[0x0E] = 'E',
		[0x0F] = 'R',
		[0x10] = 'Y',
		[0x11] = 'T',
		[0x1F] = 'O',
		[0x20] = 'U',
		[0x22] = 'I',
		[0x23] = 'P',
		[0x25] = 'L',
		[0x26] = 'J',
		[0x28] = 'K',
		[0x2D] = 'N',
		[0x2E] = 'M',

		[0x1D] = '0',
		[0x12] = '1',
		[0x13] = '2',
		[0x14] = '3',
		[0x15] = '4',
		[0x17] = '5',
		[0x16] = '6',
		[0x1A] = '7',
		[0x1C] = '8',
		[0x19] = '9',

		[0x7A] = 0x70, // F1
		[0x78] = 0x71,
		[0x63] = 0x72,
		[0x76] = 0x73,
		[0x60] = 0x74,
		[0x61] = 0x75,
		[0x62] = 0x76,
		[0x64] = 0x77,
		[0x65] = 0x78,
		[0x6D] = 0x79,
		[0x67] = 0x7A,
		[0x6F] = 0x7B,
		[0x69] = 0x7C,
		[0x6B] = 0x7D,
		[0x71] = 0x7E,
		[0x6A] = 0x7F,
		[0x40] = 0x80,
		[0x4F] = 0x81,
		[0x50] = 0x82,
		[0x5A] = 0x83, // F20

		[0x24] = 0x0D, // Return
		[0x4C] = 0x0D, // keypad Enter, which Windows also reports as Enter
		[0x30] = 0x09, // Tab
		[0x31] = 0x20, // Space
		[0x33] = 0x08, // Delete, the key Windows calls Backspace
		[0x35] = 0x1B, // Escape
		[0x72] = 0x2D, // Help, in the Insert position on a PC keyboard
		[0x75] = 0x2E, // Forward Delete
		[0x73] = 0x24, // Home
		[0x77] = 0x23, // End
		[0x74] = 0x21, // Page Up
		[0x79] = 0x22, // Page Down
		[0x7B] = 0x25, // Left
		[0x7E] = 0x26, // Up
		[0x7C] = 0x27, // Right
		[0x7D] = 0x28, // Down
		[0x6E] = 0x5D, // Context menu

		[0x52] = 0x60, // keypad 0
		[0x53] = 0x61,
		[0x54] = 0x62,
		[0x55] = 0x63,
		[0x56] = 0x64,
		[0x57] = 0x65,
		[0x58] = 0x66,
		[0x59] = 0x67,
		[0x5B] = 0x68,
		[0x5C] = 0x69, // keypad 9
		[0x43] = 0x6A, // keypad *
		[0x45] = 0x6B, // keypad +
		[0x4E] = 0x6D, // keypad -
		[0x41] = 0x6E, // keypad .
		[0x4B] = 0x6F, // keypad /

		[0x4A] = 0xAD, // Mute
		[0x49] = 0xAE, // Volume Down
		[0x48] = 0xAF, // Volume Up

		[0x29] = 0xBA, // ;
		[0x18] = 0xBB, // =
		[0x2B] = 0xBC, // ,
		[0x1B] = 0xBD, // -
		[0x2F] = 0xBE, // .
		[0x2C] = 0xBF, // /
		[0x32] = 0xC0, // `
		[0x21] = 0xDB, // [
		[0x2A] = 0xDC, // \
		[0x1E] = 0xDD, // ]
		[0x27] = 0xDE, // '
	};

	/// <summary>
	/// Each modifier's device-dependent bit in <c>CGEventFlags</c>, the only part of the flags that tells
	/// the left key from the right one.
	/// </summary>
	public static IReadOnlyList<(int VirtualKey, ulong FlagMask)> ModifierFlags { get; } =
	[
		(VirtualKeys.LControl, 0x00000001),
		(VirtualKeys.LShift, 0x00000002),
		(VirtualKeys.RShift, 0x00000004),
		(VirtualKeys.LWin, 0x00000008),
		(VirtualKeys.RWin, 0x00000010),
		(VirtualKeys.LMenu, 0x00000020),
		(VirtualKeys.RMenu, 0x00000040),
		(VirtualKeys.RControl, 0x00002000),
	];

	public static int? ToVirtualKey(int keyCode) =>
		_virtualKeys.TryGetValue(keyCode, out var vkCode) ? vkCode : null;
}
